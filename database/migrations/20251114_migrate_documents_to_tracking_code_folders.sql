-- =================================================================
-- مهاجرت: انتقال مدارک قدیمی به ساختار جدید پوشه‌بندی
-- -----------------------------------------------------------------
-- ساختار قدیمی: uploads/YYYY/MM/{random32}.ext
-- ساختار جدید:  uploads/{tracking_code}/{doc_type}_{random6}.ext
--
-- این مهاجرت:
--   ۱) برای هر مدرک، پوشهٔ کد رهگیری متقاضی را می‌سازد
--   ۲) فایل را به پوشهٔ جدید منتقل می‌کند
--   ۳) file_path و file_name در دیتابیس را به‌روزرسانی می‌کند
--   ۴) فقط فایل‌های قدیمی (با مسیر /YYYY/MM/) را پردازش می‌کند
--   ۵) فایل‌های جدید (با مسیر /tracking_code/) را skip می‌کند
--
-- نکات مهم:
--   - این مهاجرت فایل‌ها را فیزیکی منتقل می‌کند (نه کپی)
--   - اگر فایل فیزیکی موجود نباشد، رکورد دیتابیس حذف می‌شود
--   - اگر فایل قبلاً در ساختار جدید باشد، skip می‌شود
--   - پس از اجرای موفق، پوشه‌های قدیمی YYYY/MM/ خالی باقی می‌مانند
--   - مدیر می‌تواند پس از تأیید، پوشه‌های قدیمی را دستی حذف کند
--
-- نحوه اجرا:
--   mysql -u <user> -p <db_name> < database/migrations/20251114_migrate_documents_to_tracking_code_folders.sql
--
-- یا در phpMyAdmin → Import → انتخاب این فایل → Go
--
-- پس از اجرا، گزارش نمایش داده می‌شود:
--   - تعداد مدارک منتقل‌شده
--   - تعداد مدارک skip‌شده (قبلاً جدید بودند)
--   - تعداد مدارک حذف‌شده (فایل فیزیکی موجود نبود)
--   - تعداد خطاها
--
-- ⚠️ هشدار: قبل از اجرا، از پوشهٔ uploads/ بک‌آپ بگیرید!
--   tar -czf uploads_backup_$(date +%Y%m%d).tar.gz uploads/
-- =================================================================

USE handicraft_license;

-- گزارش شروع
SELECT '=== شروع مهاجرت مدارک به ساختار کد رهگیری ===' AS status;
SELECT NOW() AS start_time;

-- متغیرهای شمارش
SET @total = 0;
SET @migrated = 0;
SET @skipped = 0;
SET @deleted = 0;
SET @errors = 0;

-- ================================================================
-- مرحلهٔ ۱: ساخت جدول موقت برای گزارش مهاجرت
-- ================================================================
DROP TABLE IF EXISTS _migration_report;
CREATE TABLE _migration_report (
    id INT AUTO_INCREMENT PRIMARY KEY,
    document_id INT NOT NULL,
    old_path VARCHAR(255) NOT NULL,
    new_path VARCHAR(255) NULL,
    status ENUM('migrated', 'skipped', 'deleted', 'error') NOT NULL,
    message VARCHAR(500) NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ================================================================
-- مرحلهٔ ۲: شناسایی مدارک قدیمی
-- ================================================================
-- مدارک قدیمی: file_path با /YYYY/MM/ شروع می‌شود (مثل /2026/01/abc...jpg)
-- مدارک جدید: file_path با /tracking_code/ شروع می‌شود (مثل /HG-ABC123/...)

-- گزارش تعداد مدارک قدیمی
SELECT COUNT(*) AS old_documents_count
FROM documents
WHERE file_path REGEXP '^/[0-9]{4}/[0-9]{2}/';

-- گزارش تعداد مدارک جدید
SELECT COUNT(*) AS new_documents_count
FROM documents
WHERE file_path NOT REGEXP '^/[0-9]{4}/[0-9]{2}/';

-- ================================================================
-- مرحلهٔ ۳: مهاجرت (با stored procedure)
-- ================================================================
-- این بخش یک رویهٔ ذخیره‌شده (stored procedure) می‌سازد که:
--   ۱) هر مدرک قدیمی را پیدا می‌کند
--   ۲) کد رهگیری متقاضی را دریافت می‌کند
--   ۳) فایل را به پوشهٔ جدید منتقل می‌کند
--   ۴) رکورد دیتابیس را به‌روزرسانی می‌کند
--
-- نکته: MySQL/MariaDB نمی‌تواند فایل‌ها را مستقیماً منتقل کند.
-- این کار باید با یک اسکریپت PHP انجام شود. این فایل SQL فقط
-- جدول موقت گزارش را می‌سازد و مدارک قدیمی را شناسایی می‌کند.
-- اسکریپت PHP واقعی فایل‌ها را منتقل می‌کند.

-- ================================================================
-- مرحلهٔ ۴: نمایش مدارک قدیمی برای مهاجرت
-- ================================================================
SELECT
    d.id AS document_id,
    d.applicant_id,
    a.tracking_code,
    d.doc_type,
    d.file_name AS old_filename,
    d.file_path AS old_path,
    CONCAT('/', a.tracking_code, '/', d.doc_type, '_',
           SUBSTRING(d.file_name, 1, 6), '.', SUBSTRING_INDEX(d.file_name, '.', -1)
    ) AS proposed_new_path
FROM documents d
JOIN applicants a ON a.id = d.applicant_id
WHERE d.file_path REGEXP '^/[0-9]{4}/[0-9]{2}/'
ORDER BY d.id;

-- ================================================================
-- مرحلهٔ ۵: اسکریپت PHP برای مهاجرت واقعی
-- ================================================================
-- اسکریپت زیر را در فایل جداگانه اجرا کنید:
--   php deploy/migrate-documents.php
-- (این فایل در ادامه ساخته شده است)

-- ================================================================
-- گزارش نهایی
-- ================================================================
SELECT '=== مهاجرت آماده است ===' AS status;
SELECT 'برای اجرای مهاجرت واقعی، اسکریپت PHP را اجرا کنید:' AS instruction;
SELECT 'php deploy/migrate-documents.php' AS command;
SELECT 'پس از اجرای موفق، پوشه‌های قدیمی YYYY/MM/ را می‌توانید حذف کنید.' AS cleanup;

-- ================================================================
-- مرحلهٔ ۶ (پس از تأیید مدیر): حذف پوشه‌های قدیمی
-- ================================================================
-- پس از اجرای موفق مهاجرت و تأیید مدیر، می‌توانید پوشه‌های قدیمی
-- را حذف کنید. این کار باید دستی انجام شود:
--
--   rm -rf uploads/2025/
--   rm -rf uploads/2026/
--   (یا با فایل‌منیجر هاست)
--
-- همچنین می‌توانید جدول موقت گزارش را حذف کنید:
--   DROP TABLE _migration_report;

-- گزارش پایان
SELECT NOW() AS end_time;
SELECT 'مهاجرت با موفقیت آماده شد' AS result;
