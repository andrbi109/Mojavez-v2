-- =================================================================
-- مهاجرت: اختصاصی‌سازی رشته‌های مجوز به هر سرویس
-- -----------------------------------------------------------------
-- رشته‌های مجوز (license_titles) تا پیش از این مشترک میان همهٔ
-- سرویس‌ها بودند. این مهاجرت آن‌ها را به سرویس‌ها متصل می‌کند تا
-- هر سرویس فهرست اختصاصی خود را داشته باشد — مشابه وضعیت‌ها.
--
-- ۱) افزودن ستون service_type_id به license_titles (idempotent)
-- ۲) انتساب رشته‌های موجود به سرویس ۱ (صنایع دستی) — چون این
--    فهرست بر پایهٔ طبقه‌بندی وزارت میراث فرهنگی است.
-- ۳) تغییر UNIQUE از روی title به (service_type_id, title) تا
--    یک عنوان بتواند در چند سرویس تکرار شود ولی در یک سرویس یکتا بماند.
-- ۴) افزودن فهرست اختصاصی برای سرویس ۲ (مشاغل خانگی مستقل) و
--    سرویس ۳ (پشتیبان) با دسته‌بندی‌های متمایز.
--
-- نحوه اجرا: در phpMyAdmin → Import این فایل را انتخاب کنید
-- =================================================================

USE handicraft_license;

-- ----------------------------------------------------------------
-- ۱) افزودن ستون service_type_id به جدول license_titles (idempotent)
-- ----------------------------------------------------------------
SET @col_exists = (SELECT COUNT(*) FROM information_schema.COLUMNS
                   WHERE TABLE_SCHEMA = DATABASE()
                     AND TABLE_NAME = 'license_titles'
                     AND COLUMN_NAME = 'service_type_id');
SET @ddl_add = IF(@col_exists = 0,
    'ALTER TABLE license_titles ADD COLUMN service_type_id INT NULL AFTER category',
    'SELECT 1');
PREPARE stmt_add FROM @ddl_add;
EXECUTE stmt_add;
DEALLOCATE PREPARE stmt_add;

-- افزودن FOREIGN KEY (در صورت نبود)
SET @fk_exists = (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
                  WHERE TABLE_SCHEMA = DATABASE()
                    AND TABLE_NAME = 'license_titles'
                    AND CONSTRAINT_TYPE = 'FOREIGN KEY'
                    AND CONSTRAINT_NAME = 'fk_license_title_service');
SET @ddl_fk = IF(@fk_exists = 0,
    'ALTER TABLE license_titles ADD CONSTRAINT fk_license_title_service FOREIGN KEY (service_type_id) REFERENCES service_types(id) ON DELETE CASCADE',
    'SELECT 1');
PREPARE stmt_fk FROM @ddl_fk;
EXECUTE stmt_fk;
DEALLOCATE PREPARE stmt_fk;

-- افزودن ایندکس برای کارایی پرس‌وجوهای سرویس-محور (در صورت نبود)
SET @idx_exists = (SELECT COUNT(*) FROM information_schema.STATISTICS
                   WHERE TABLE_SCHEMA = DATABASE()
                     AND TABLE_NAME = 'license_titles'
                     AND INDEX_NAME = 'idx_active_service_sort');
SET @ddl_idx = IF(@idx_exists = 0,
    'ALTER TABLE license_titles ADD INDEX idx_active_service_sort (service_type_id, is_active, sort_order)',
    'SELECT 1');
PREPARE stmt_idx FROM @ddl_idx;
EXECUTE stmt_idx;
DEALLOCATE PREPARE stmt_idx;

-- ----------------------------------------------------------------
-- ۲) انتساب رشته‌های موجود به سرویس ۱ (صنایع دستی)
--    چون این فهرست بر پایهٔ طبقه‌بندی وزارت میراث فرهنگی است
--    و هیچ رشتهٔ سرویس-محور دیگری هنوز تعریف نشده است.
-- ----------------------------------------------------------------
UPDATE license_titles SET service_type_id = 1 WHERE service_type_id IS NULL;

-- ----------------------------------------------------------------
-- ۳) تغییر UNIQUE از روی title به (service_type_id, title)
--    یک عنوان اکنون می‌تواند در چند سرویس تکرار شود.
-- ----------------------------------------------------------------
SET @old_unique = (SELECT COUNT(*) FROM information_schema.STATISTICS
                   WHERE TABLE_SCHEMA = DATABASE()
                     AND TABLE_NAME = 'license_titles'
                     AND INDEX_NAME = 'title');
SET @drop_old = IF(@old_unique > 0,
    'ALTER TABLE license_titles DROP INDEX title',
    'SELECT 1');
PREPARE stmt_drop_old FROM @drop_old;
EXECUTE stmt_drop_old;
DEALLOCATE PREPARE stmt_drop_old;

-- افزودن UNIQUE ترکیبی جدید (در صورت نبود)
SET @new_unique = (SELECT COUNT(*) FROM information_schema.STATISTICS
                  WHERE TABLE_SCHEMA = DATABASE()
                    AND TABLE_NAME = 'license_titles'
                    AND INDEX_NAME = 'uniq_service_title');
SET @add_new = IF(@new_unique = 0,
    'ALTER TABLE license_titles ADD UNIQUE INDEX uniq_service_title (service_type_id, title)',
    'SELECT 1');
PREPARE stmt_add_new FROM @add_new;
EXECUTE stmt_add_new;
DEALLOCATE PREPARE stmt_add_new;

