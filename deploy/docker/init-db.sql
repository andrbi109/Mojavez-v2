-- ============================================================
-- init-db.sql — اسکریپت مقداردهی اولیهٔ MariaDB
-- ------------------------------------------------------------
-- این فایل توسط کانتینر MariaDB در مسیر /docker-entrypoint-initdb.d/
-- هنگام نخستین راه‌اندازی (زمانی که volume خالی است) به‌عنوان root
-- اجرا می‌شود.
--
-- نقش: یک «wrapper» سبک. اجرای اصلی schema.sql توسط entrypoint.sh
-- کانتینر app انجام می‌شود (وقتی INIT_DB=1 باشد)؛ بنابراین این فایل
-- عمداً سبک نگه داشته شده و فقط یک کامنت است.
--
-- توضیح دربارهٔ چرایی خالی بودن:
--   • پایگاه داده و کاربر توسط متغیرهای MYSQL_DATABASE و MYSQL_USER
--     در docker-compose ساخته می‌شوند.
--   • کاراکترست utf8mb4 توسط متغیرهای MARIADB_CHARACTER_SET و
--     MARIADB_COLLATION تضمین می‌شود.
--   • جداول توسط entrypoint.sh (با INIT_DB=1) از روی schema.sql ساخته
--     می‌شوند.
--
-- اگر در آینده خواستید مقداردهی اضافی (مثل درج کاربر مدیر پیش‌فرض،
-- داده‌های اولیه و ...) انجام دهید، دستورات SQL خود را در این فایل
-- اضافه کنید. مثال (غیرفعال):
--
--   USE handicraft_license;
--   INSERT IGNORE INTO users (username, password, display_name)
--   VALUES ('admin', '<bcrypt-hash>', 'مدیر سامانه');
--
-- پایان
-- ============================================================
